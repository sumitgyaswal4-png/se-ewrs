def _sql_str(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    escaped = str(value).replace("\\", "\\\\").replace("'", "''")
    return f"'{escaped}'"


def _sql_date(offset: Optional[int]) -> str:
    """``CURDATE()`` arithmetic so the demo data never goes stale."""
    if offset is None:
        return "NULL"
    if offset == 0:
        return "CURDATE()"
    return f"(CURDATE() - INTERVAL {offset} DAY)"


def _sql_datetime(offset: Optional[int], minute: Optional[int]) -> str:
    if offset is None:
        return "NULL"
    base = "CURDATE()" if offset == 0 else f"(CURDATE() - INTERVAL {offset} DAY)"
    if not minute:
        return f"TIMESTAMP({base})"
    return f"(TIMESTAMP({base}) + INTERVAL {minute} MINUTE)"


def _insert_block(table: str, columns: List[str], rows: List[List[str]], chunk: int = 100) -> str:
    """Multi-row INSERTs in chunks, which keeps the file readable and fast."""
    if not rows:
        return f"-- (no rows for {table})\n"
    parts = [f"-- {len(rows)} row(s) into {table}"]
    column_list = ", ".join(columns)
    for start in range(0, len(rows), chunk):
        block = rows[start : start + chunk]
        values = ",\n    ".join(f"({', '.join(r)})" for r in block)
        parts.append(f"INSERT INTO {table} ({column_list}) VALUES\n    {values};")
    return "\n".join(parts) + "\n"


