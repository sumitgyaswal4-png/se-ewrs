"""Demo data generator for SE-EWRS.

One dataset definition, two outputs:

* ``python -m app.db.seed`` inserts it through SQLAlchemy into whatever
  ``DATABASE_URL`` / ``DB_*`` points at (MySQL 8 or SQLite), then runs the
  risk engine so risk rows and alerts are generated by the real code.
* ``python -m app.db.seed --emit-sql ../database/seed.sql`` renders the
  same dataset as a standalone MySQL script.

Every identity in here is fictional. No real student record or personal
data is included.

All dates are stored as *offsets in days from today* rather than as fixed
calendar dates, so the emitted ``seed.sql`` writes
``CURDATE() - INTERVAL n DAY`` and the demo stays realistic no matter when
it is loaded -- a fixed date would make every student look disengaged a
few months later.
"""

