@dataclass
class Dataset:
    """Fully-resolved demo rows with explicit primary keys.

    Primary keys are assigned here rather than left to AUTO_INCREMENT so
    the SQL and ORM paths produce identical foreign keys.
    """

    departments: List[tuple] = field(default_factory=list)
    users: List[dict] = field(default_factory=list)
    students: List[dict] = field(default_factory=list)
    courses: List[dict] = field(default_factory=list)
    course_instructors: List[dict] = field(default_factory=list)
    enrollments: List[dict] = field(default_factory=list)
    attendance: List[dict] = field(default_factory=list)
    activities: List[dict] = field(default_factory=list)
    assessments: List[dict] = field(default_factory=list)
    results: List[dict] = field(default_factory=list)
    interventions: List[dict] = field(default_factory=list)
    #: enrollment_id -> cohort name, used by the summary print-out.
    cohort_by_enrollment: Dict[int, str] = field(default_factory=dict)

    def counts(self) -> Dict[str, int]:
        return {
            "departments": len(self.departments),
            "users": len(self.users),
            "students": len(self.students),
            "courses": len(self.courses),
            "course_instructors": len(self.course_instructors),
            "enrollments": len(self.enrollments),
            "attendance_records": len(self.attendance),
            "lms_activity_logs": len(self.activities),
            "assessments": len(self.assessments),
            "assessment_results": len(self.results),
            "interventions": len(self.interventions),
        }


def _clamp(value: float, low: float, high: float) -> float:
    return max(low, min(high, value))


def build_dataset(seed: int = RANDOM_SEED) -> Dataset:
    """Produce the demo dataset deterministically."""
    rng = random.Random(seed)
    data = Dataset(departments=list(DEPARTMENTS))

    # --- users ------------------------------------------------------------
    for user_id, full_name, email, role, dept_id in USERS:
        data.users.append(
            {
                "user_id": user_id,
                "full_name": full_name,
                "email": email,
                "role": role,
                "dept_id": dept_id,
                "phone": f"+91-90000-{10000 + user_id}",
                "last_login_offset_days": rng.randint(0, 6),
            }
        )

    # --- students ---------------------------------------------------------
    cohort_by_name = {c.name: c for c in COHORTS}
    assignments: List[str] = []
    for name, count in COHORT_SIZES.items():
        assignments.extend([name] * count)
    rng.shuffle(assignments)

    # Most students sit in Mathematics; a few in the other departments so
    # the department-level reports have something to compare.
    dept_plan = [1] * 24 + [2] * 6 + [3] * 4 + [4] * 2
    rng.shuffle(dept_plan)

    dept_prefix = {1: "MTH", 2: "CSE", 3: "STA", 4: "PHY"}
    counters: Dict[int, int] = {1: 0, 2: 0, 3: 0, 4: 0}
    used_names = set()

    for index, cohort_name in enumerate(assignments, start=1):
        dept_id = dept_plan[index - 1]
        counters[dept_id] += 1
        # Semester 3 / 5 / 7 so students line up with the course catalogue.
        semester = [3, 3, 3, 5, 5, 7][index % 6]
        enrollment_year = {3: 2024, 5: 2023, 7: 2022}[semester]

        while True:
            full_name = f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}"
            if full_name not in used_names:
                used_names.add(full_name)
                break

        roll = f"{dept_prefix[dept_id]}{enrollment_year}{counters[dept_id]:03d}"
        local = full_name.lower().replace(" ", ".")
        data.students.append(
            {
                "student_pk": index,
                "student_id": roll,
                "full_name": full_name,
                "email": f"{local}.{index}@students.se-ewrs.edu",
                "dept_id": dept_id,
                "semester": semester,
                "enrollment_year": enrollment_year,
                "phone": f"+91-98{rng.randint(10000000, 99999999)}",
                "cohort": cohort_name,
            }
        )

    # --- courses ----------------------------------------------------------
    for course_pk, code, name, dept_id, semester, credits, sessions in COURSES:
        data.courses.append(
            {
                "course_pk": course_pk,
                "course_code": code,
                "course_name": name,
                "dept_id": dept_id,
                "semester": semester,
                "credits": credits,
                "academic_term": TERM,
                "total_sessions": sessions,
            }
        )
    for ci_id, course_pk, user_id, role_in_course in COURSE_INSTRUCTORS:
        data.course_instructors.append(
            {
                "course_instructor_id": ci_id,
                "course_pk": course_pk,
                "user_id": user_id,
                "role_in_course": role_in_course,
            }
        )

    # --- assessments ------------------------------------------------------
    assessment_id = 0
    assessments_by_course: Dict[int, List[dict]] = {c[0]: [] for c in COURSES}
    for course in data.courses:
        for suffix, a_type, max_marks, weight, due_offset in ASSESSMENT_PLAN:
            assessment_id += 1
            row = {
                "assessment_id": assessment_id,
                "course_pk": course["course_pk"],
                "title": f"{course['course_code']} {suffix}",
                "assessment_type": a_type,
                "max_marks": max_marks,
                "weight_percent": weight,
                "due_at_offset_days": due_offset,
                "due_at_minute": 17 * 60,  # 17:00
                "created_by": _primary_instructor(course["course_pk"]),
            }
            data.assessments.append(row)
            assessments_by_course[course["course_pk"]].append(row)

    # --- enrolments, attendance, activity, results ------------------------
    courses_for_semester: Dict[int, List[int]] = {3: [1, 2, 5], 5: [3, 6], 7: [4]}
    enrollment_id = 0
    attendance_id = 0
    activity_id = 0
    result_id = 0

    for student in data.students:
        cohort = cohort_by_name[student["cohort"]]
        pool = list(courses_for_semester[student["semester"]])
        # Semester 7 has a single course in the catalogue; give those
        # students a second enrolment from semester 5 so the demo has
        # students appearing in more than one course.
        if student["semester"] == 7:
            pool.append(3)
        rng.shuffle(pool)
        take = min(len(pool), 2 if student["semester"] != 3 else rng.choice([2, 3]))
        chosen = pool[:take]

        for course_pk in chosen:
            enrollment_id += 1
            course = next(c for c in data.courses if c["course_pk"] == course_pk)
            data.enrollments.append(
                {
                    "enrollment_id": enrollment_id,
                    "student_pk": student["student_pk"],
                    "course_pk": course_pk,
                    "enrolled_on_offset_days": 95,
                    "status": "ACTIVE",
                }
            )
            data.cohort_by_enrollment[enrollment_id] = cohort.name

            if cohort.name == "newly_enrolled":
                # Deliberately almost no data: this is what produces the
                # INSUFFICIENT_DATA rows the risk page has to explain.
                # One login, nothing else.
                activity_id += 1
                data.activities.append(
                    {
                        "activity_id": activity_id,
                        "enrollment_id": enrollment_id,
                        "activity_type": "LOGIN",
                        "at_offset_days": 2,
                        "at_minute": 10 * 60 + 15,
                        "duration_minutes": 6,
                        "resource_ref": None,
                    }
                )
                continue

            # ---- attendance -------------------------------------------
            sessions = course["total_sessions"]
            target = rng.uniform(*cohort.attendance)
            # Sessions run roughly twice a week over the last ~12 weeks.
            for session_index in range(sessions):
                offset = 88 - session_index * 3 - rng.choice([0, 1])
                if offset < 1:
                    continue
                attendance_id += 1
                roll = rng.random()
                if roll < target:
                    status = "PRESENT"
                elif roll < target + 0.06:
                    status = "LATE"
                elif roll < target + 0.09:
                    status = "EXCUSED"
                else:
                    status = "ABSENT"
                data.attendance.append(
                    {
                        "attendance_id": attendance_id,
                        "enrollment_id": enrollment_id,
                        "session_offset_days": offset,
                        "session_no": 1,
                        "status": status,
                        "recorded_by": _course_ta(course_pk),
                        "remarks": "Medical leave on record" if status == "EXCUSED" else None,
                    }
                )

            # ---- LMS activity ------------------------------------------
            last_seen = rng.randint(*cohort.last_seen_days)
            per_week = rng.randint(*cohort.logins_per_week)
            for week in range(12):
                week_start = last_seen + week * 7
                for _ in range(per_week):
                    offset = week_start + rng.randint(0, 6)
                    if offset < last_seen or offset > 95:
                        continue
                    activity_id += 1
                    data.activities.append(
                        {
                            "activity_id": activity_id,
                            "enrollment_id": enrollment_id,
                            "activity_type": "LOGIN",
                            "at_offset_days": offset,
                            "at_minute": rng.randint(8, 22) * 60 + rng.randint(0, 59),
                            "duration_minutes": rng.randint(4, 55),
                            "resource_ref": None,
                        }
                    )
                    # A login usually comes with a resource view.
                    if rng.random() < 0.7:
                        activity_id += 1
                        data.activities.append(
                            {
                                "activity_id": activity_id,
                                "enrollment_id": enrollment_id,
                                "activity_type": rng.choice(
                                    ["RESOURCE_VIEW", "VIDEO_WATCH", "FORUM_POST"]
                                ),
                                "at_offset_days": offset,
                                "at_minute": rng.randint(8, 22) * 60 + rng.randint(0, 59),
                                "duration_minutes": rng.randint(3, 40),
                                "resource_ref": rng.choice(RESOURCE_REFS),
                            }
                        )
            # Guarantee the most recent event matches the cohort's
            # "last seen" value exactly, so days_since_last_activity is
            # not left to chance.
            activity_id += 1
            data.activities.append(
                {
                    "activity_id": activity_id,
                    "enrollment_id": enrollment_id,
                    "activity_type": "LOGIN",
                    "at_offset_days": last_seen,
                    "at_minute": 19 * 60 + 30,
                    "duration_minutes": rng.randint(5, 30),
                    "resource_ref": None,
                }
            )

            # ---- assessment results ------------------------------------
            marks_centre = rng.uniform(*cohort.marks)
            for assessment in assessments_by_course[course_pk]:
                result_id += 1
                due_offset = assessment["due_at_offset_days"]
                roll = rng.random()

                if roll < cohort.missing_probability:
                    submitted_offset = None
                    submitted_minute = None
                    marks = None
                    status = "MISSING"
                elif roll < cohort.missing_probability + cohort.late_probability:
                    submitted_offset = max(due_offset - rng.randint(1, 4), 0)
                    submitted_minute = rng.randint(9, 23) * 60
                    status = "LATE"
                    marks = None
                else:
                    submitted_offset = due_offset + rng.randint(0, 3)
                    submitted_minute = rng.randint(9, 16) * 60
                    status = "ON_TIME"
                    marks = None

                if status != "MISSING":
                    pct = _clamp(rng.gauss(marks_centre, 7.5), 5, 100)
                    if status == "LATE":
                        pct = _clamp(pct - 6, 3, 100)
                    marks = round(assessment["max_marks"] * pct / 100, 2)
                    if marks > assessment["max_marks"]:
                        marks = float(assessment["max_marks"])

                # A quiz attempt leaves an LMS trace too.
                if status != "MISSING" and assessment["assessment_type"] == "QUIZ":
                    activity_id += 1
                    data.activities.append(
                        {
                            "activity_id": activity_id,
                            "enrollment_id": enrollment_id,
                            "activity_type": "QUIZ_ATTEMPT",
                            "at_offset_days": submitted_offset,
                            "at_minute": submitted_minute,
                            "duration_minutes": rng.randint(10, 30),
                            "resource_ref": assessment["title"],
                        }
                    )
                elif status != "MISSING" and assessment["assessment_type"] == "ASSIGNMENT":
                    activity_id += 1
                    data.activities.append(
                        {
                            "activity_id": activity_id,
                            "enrollment_id": enrollment_id,
                            "activity_type": "ASSIGNMENT_SUBMIT",
                            "at_offset_days": submitted_offset,
                            "at_minute": submitted_minute,
                            "duration_minutes": None,
                            "resource_ref": assessment["title"],
                        }
                    )

                data.results.append(
                    {
                        "result_id": result_id,
                        "assessment_id": assessment["assessment_id"],
                        "enrollment_id": enrollment_id,
                        "marks_obtained": marks,
                        "submitted_at_offset_days": submitted_offset,
                        "submitted_at_minute": submitted_minute,
                        "submission_status": status,
                        "attempt_no": 1,
                        "graded_by": _primary_instructor(course_pk),
                        "graded_offset_days": (
                            max(due_offset - 5, 0) if marks is not None else None
                        ),
                        "max_marks": assessment["max_marks"],
                    }
                )

    # --- interventions ----------------------------------------------------
    struggling = [
        eid for eid, name in data.cohort_by_enrollment.items() if name == "struggling"
    ]
    borderline = [
        eid for eid, name in data.cohort_by_enrollment.items() if name == "borderline"
    ]
    plan = [
        ("COUNSELING", 8, "IMPROVED", "CLOSED", 26, 12),
        ("ATTENDANCE_FOLLOWUP", 9, "NO_CHANGE", "IN_PROGRESS", 21, 7),
        ("TUTORING_REFERRAL", 8, "IMPROVED", "CLOSED", 30, 16),
        ("ASSIGNMENT_SUPPORT", 2, "PENDING", "OPEN", 6, None),
        ("ACADEMIC_ADVISING", 9, "ESCALATED", "IN_PROGRESS", 14, 3),
        ("COUNSELING", 8, "DECLINED", "CLOSED", 33, None),
        ("TUTORING_REFERRAL", 9, "PENDING", "OPEN", 4, None),
        ("ATTENDANCE_FOLLOWUP", 6, "IMPROVED", "CLOSED", 19, 5),
        ("PARENT_CONTACT", 8, "NO_CHANGE", "IN_PROGRESS", 11, 2),
        ("ACADEMIC_ADVISING", 9, "IMPROVED", "CLOSED", 28, 14),
        ("ASSIGNMENT_SUPPORT", 3, "PENDING", "OPEN", 5, None),
        ("COUNSELING", 8, "PENDING", "IN_PROGRESS", 9, None),
    ]
    notes = {
        "COUNSELING": (
            "Met the student in person. They reported difficulty keeping up after "
            "missing two weeks of classes.",
            "Weekly 20-minute check-in; agreed catch-up plan for the missed topics.",
        ),
        "ATTENDANCE_FOLLOWUP": (
            "Attendance has fallen below the 75% requirement for this course.",
            "Student to confirm attendance each week; TA to flag any further absence.",
        ),
        "TUTORING_REFERRAL": (
            "Assessment average is well below the course mean, concentrated in the "
            "problem-solving sections.",
            "Referred to the peer tutoring centre for two sessions a week.",
        ),
        "ASSIGNMENT_SUPPORT": (
            "Two assignments were submitted late and one is still outstanding.",
            "Extended deadline agreed; instructor to review a draft before submission.",
        ),
        "ACADEMIC_ADVISING": (
            "Reviewed the overall course load with the student; they are at risk in "
            "more than one subject.",
            "Considering dropping one elective to protect the core courses.",
        ),
        "PARENT_CONTACT": (
            "Contacted the registered guardian after repeated non-response from the "
            "student.",
            "Guardian to confirm the student's circumstances within a week.",
        ),
    }

    pool = struggling + borderline
    intervention_id = 0
    for index, (i_type, advisor, outcome, resolution, contact_offset, follow_offset) in enumerate(
        plan
    ):
        if not pool:
            break
        enrollment_id = pool[index % len(pool)]
        intervention_id += 1
        note, plan_text = notes[i_type]
        data.interventions.append(
            {
                "intervention_id": intervention_id,
                "enrollment_id": enrollment_id,
                "intervention_type": i_type,
                "assigned_advisor_id": advisor,
                "contact_offset_days": contact_offset,
                "notes": note,
                "action_plan": plan_text,
                "follow_up_offset_days": follow_offset,
                "outcome": outcome,
                "resolution_status": resolution,
                "created_by": advisor,
            }
        )

    return data


def _primary_instructor(course_pk: int) -> int:
    for _, pk, user_id, role in COURSE_INSTRUCTORS:
        if pk == course_pk and role == "PRIMARY":
            return user_id
    return 1


def _course_ta(course_pk: int) -> int:
    for _, pk, user_id, role in COURSE_INSTRUCTORS:
        if pk == course_pk and role == "TA":
            return user_id
    return _primary_instructor(course_pk)


# ===========================================================================
# Date helpers
# ===========================================================================
def _day(offset: Optional[int], today: date) -> Optional[date]:
    return None if offset is None else today - timedelta(days=offset)


def _moment(offset: Optional[int], minute: Optional[int], today: date) -> Optional[datetime]:
    if offset is None:
        return None
    base = datetime.combine(today - timedelta(days=offset), datetime.min.time())
    return base + timedelta(minutes=minute or 0)


