def seed_database(
    url: Optional[str] = None,
    reset: bool = True,
    recalculate: bool = True,
    quiet: bool = False,
) -> Dict[str, int]:
    """Populate the configured database with the demo dataset.

    ``reset=True`` clears the tables listed in ``SEED_TABLES`` first --
    and only those. ``system_settings`` is left alone so a tuned risk
    model survives a reseed.
    """
    from sqlalchemy import create_engine, delete, text
    from sqlalchemy.orm import Session

    from app.core.security import hash_password
    from app.db.base import Base
    from app.models import (
        Assessment,
        AssessmentResult,
        AttendanceRecord,
        Course,
        CourseInstructor,
        Department,
        Enrollment,
        Intervention,
        LmsActivityLog,
        Student,
        SystemSetting,
        User,
    )
    from app.services import risk_engine

    if url:
        engine = create_engine(url)
    else:
        from app.db.session import engine as configured_engine

        engine = configured_engine

    def log(message: str) -> None:
        if not quiet:
            print(message)

    Base.metadata.create_all(engine)
    today = date.today()
    data = build_dataset()

    # One Argon2 hash reused for every demo account: hashing 11 times with
    # the same password would only waste a second of start-up time.
    demo_hash = hash_password(DEMO_PASSWORD)

    with Session(engine) as db:
        if reset:
            log("Clearing demo tables...")
            is_mysql = engine.dialect.name == "mysql"
            if is_mysql:
                db.execute(text("SET FOREIGN_KEY_CHECKS = 0"))
            else:
                db.execute(text("PRAGMA foreign_keys = OFF"))
            for table_name in SEED_TABLES:
                table = Base.metadata.tables.get(table_name)
                if table is not None:
                    db.execute(delete(table))
            if is_mysql:
                db.execute(text("SET FOREIGN_KEY_CHECKS = 1"))
            else:
                db.execute(text("PRAGMA foreign_keys = ON"))
            db.commit()

        # --- reference data --------------------------------------------
        db.add_all(
            [
                Department(dept_id=dept_id, dept_code=code, dept_name=name)
                for dept_id, code, name in data.departments
            ]
        )
        db.add_all(
            [
                User(
                    user_id=row["user_id"],
                    full_name=row["full_name"],
                    email=row["email"],
                    password_hash=demo_hash,
                    role=row["role"],
                    dept_id=row["dept_id"],
                    phone=row["phone"],
                    is_active=True,
                    last_login_at=_moment(row["last_login_offset_days"], 9 * 60, today),
                )
                for row in data.users
            ]
        )
        db.add_all(
            [
                Student(
                    student_pk=row["student_pk"],
                    student_id=row["student_id"],
                    full_name=row["full_name"],
                    email=row["email"],
                    dept_id=row["dept_id"],
                    semester=row["semester"],
                    enrollment_year=row["enrollment_year"],
                    phone=row["phone"],
                    is_active=True,
                )
                for row in data.students
            ]
        )
        db.add_all(
            [
                Course(
                    course_pk=row["course_pk"],
                    course_code=row["course_code"],
                    course_name=row["course_name"],
                    dept_id=row["dept_id"],
                    semester=row["semester"],
                    credits=row["credits"],
                    academic_term=row["academic_term"],
                    total_sessions=row["total_sessions"],
                    is_active=True,
                )
                for row in data.courses
            ]
        )
        db.flush()
        db.add_all(
            [
                CourseInstructor(
                    course_instructor_id=row["course_instructor_id"],
                    course_pk=row["course_pk"],
                    user_id=row["user_id"],
                    role_in_course=row["role_in_course"],
                )
                for row in data.course_instructors
            ]
        )
        db.add_all(
            [
                Enrollment(
                    enrollment_id=row["enrollment_id"],
                    student_pk=row["student_pk"],
                    course_pk=row["course_pk"],
                    enrolled_on=_day(row["enrolled_on_offset_days"], today),
                    status=row["status"],
                )
                for row in data.enrollments
            ]
        )
        db.flush()

        # --- engagement facts -------------------------------------------
        log(f"Inserting {len(data.attendance)} attendance records...")
        db.bulk_insert_mappings(
            AttendanceRecord,
            [
                {
                    "attendance_id": row["attendance_id"],
                    "enrollment_id": row["enrollment_id"],
                    "session_date": _day(row["session_offset_days"], today),
                    "session_no": row["session_no"],
                    "status": row["status"],
                    "recorded_by": row["recorded_by"],
                    "remarks": row["remarks"],
                }
                for row in data.attendance
            ],
        )
        log(f"Inserting {len(data.activities)} LMS activity rows...")
        db.bulk_insert_mappings(
            LmsActivityLog,
            [
                {
                    "activity_id": row["activity_id"],
                    "enrollment_id": row["enrollment_id"],
                    "activity_type": row["activity_type"],
                    "activity_at": _moment(row["at_offset_days"], row["at_minute"], today),
                    "duration_minutes": row["duration_minutes"],
                    "resource_ref": row["resource_ref"],
                }
                for row in data.activities
            ],
        )
        db.add_all(
            [
                Assessment(
                    assessment_id=row["assessment_id"],
                    course_pk=row["course_pk"],
                    title=row["title"],
                    assessment_type=row["assessment_type"],
                    max_marks=row["max_marks"],
                    weight_percent=row["weight_percent"],
                    due_at=_moment(row["due_at_offset_days"], row["due_at_minute"], today),
                    created_by=row["created_by"],
                )
                for row in data.assessments
            ]
        )
        db.flush()

        log(f"Inserting {len(data.results)} assessment results...")
        result_rows = []
        for row in data.results:
            marks = row["marks_obtained"]
            percentage = (
                None
                if marks is None
                else round(100.0 * float(marks) / float(row["max_marks"]), 2)
            )
            result_rows.append(
                {
                    "result_id": row["result_id"],
                    "assessment_id": row["assessment_id"],
                    "enrollment_id": row["enrollment_id"],
                    "marks_obtained": marks,
                    "percentage": percentage,
                    "submitted_at": _moment(
                        row["submitted_at_offset_days"], row["submitted_at_minute"], today
                    ),
                    "submission_status": row["submission_status"],
                    "attempt_no": row["attempt_no"],
                    "graded_by": row["graded_by"] if marks is not None else None,
                    "graded_at": _moment(row["graded_offset_days"], 15 * 60, today),
                }
            )
        db.bulk_insert_mappings(AssessmentResult, result_rows)

        # --- settings (inserted only if absent) --------------------------
        _ensure_settings(db, SystemSetting)
        db.commit()

        # --- risk scores and alerts via the real engine ------------------
        if recalculate:
            log("Running the risk engine over every active enrolment...")
            processed = risk_engine.recalculate_all(db, actor_user_id=1)
            log(f"  scored {processed} enrolments")

        # --- interventions, linked to the alerts just raised -------------
        from app.models import RiskAlert

        open_alerts = {
            alert.enrollment_id: alert.alert_id
            for alert in db.execute(
                __import__("sqlalchemy").select(RiskAlert).where(RiskAlert.active_flag == 1)
            ).scalars()
        }
        db.add_all(
            [
                Intervention(
                    intervention_id=row["intervention_id"],
                    enrollment_id=row["enrollment_id"],
                    alert_id=open_alerts.get(row["enrollment_id"]),
                    intervention_type=row["intervention_type"],
                    assigned_advisor_id=row["assigned_advisor_id"],
                    contact_date=_day(row["contact_offset_days"], today),
                    notes=row["notes"],
                    action_plan=row["action_plan"],
                    follow_up_date=_day(row["follow_up_offset_days"], today),
                    outcome=row["outcome"],
                    resolution_status=row["resolution_status"],
                    created_by=row["created_by"],
                )
                for row in data.interventions
            ]
        )
        db.commit()

        # --- a few alerts moved along, so the demo has a worked queue ----
        _advance_some_alerts(db)

        counts = data.counts()
        counts["risk_assessments"] = db.execute(
            text("SELECT COUNT(*) FROM risk_assessments")
        ).scalar_one()
        counts["risk_alerts"] = db.execute(
            text("SELECT COUNT(*) FROM risk_alerts")
        ).scalar_one()
        return counts


def _ensure_settings(db, SystemSetting) -> None:
    """Insert the default risk-model settings if they are not present.

    A reseed must not silently reset a tuned model, so existing keys are
    left exactly as they are.
    """
    from sqlalchemy import select

    defaults = [
        ("risk.weight.attendance", "0.35", "FLOAT",
         "Weight of the attendance component in the risk score"),
        ("risk.weight.academic", "0.40", "FLOAT",
         "Weight of the academic component in the risk score"),
        ("risk.weight.engagement", "0.25", "FLOAT",
         "Weight of the engagement component in the risk score"),
        ("risk.threshold.medium", "30", "INT",
         "Lowest risk score classified as MEDIUM risk"),
        ("risk.threshold.high", "60", "INT",
         "Lowest risk score classified as HIGH risk"),
        ("risk.min_sessions", "3", "INT",
         "Attendance sessions required before the attendance component counts"),
        ("risk.min_graded", "1", "INT",
         "Graded assessments required before the academic component counts"),
        ("risk.activity_window_days", "30", "INT",
         "Look-back window in days for LMS login frequency"),
        ("alert.min_score", "30", "INT",
         "Risk score at or above which an early-warning alert is raised"),
        ("engagement.target_logins_30d", "12", "INT",
         "Login count in the window that earns a full engagement score"),
        ("risk.model_version", "rule-v1", "STRING",
         "Identifier of the active scoring model"),
    ]
    existing = set(db.execute(select(SystemSetting.setting_key)).scalars())
    for key, value, value_type, description in defaults:
        if key not in existing:
            db.add(
                SystemSetting(
                    setting_key=key,
                    setting_value=value,
                    value_type=value_type,
                    description=description,
                )
            )


def _advance_some_alerts(db) -> None:
    """Move a handful of alerts past NEW so the queue looks worked-on."""
    from sqlalchemy import select

    from app.models import AlertStatusHistory, RiskAlert

    alerts = list(
        db.execute(
            select(RiskAlert).where(RiskAlert.status == "NEW").order_by(RiskAlert.alert_id)
        ).scalars()
    )
    plan = [
        ("ACKNOWLEDGED", 8, "Reviewed in the weekly advising meeting."),
        ("IN_PROGRESS", 8, "Counselling session booked with the student."),
        ("ACKNOWLEDGED", 9, "Contacted the student by email; awaiting a reply."),
        ("IN_PROGRESS", 9, "Tutoring referral raised."),
        ("ACKNOWLEDGED", 2, "Discussed with the course instructor."),
    ]
    now = datetime.now()
    for alert, (new_status, user_id, note) in zip(alerts, plan):
        alert.status = new_status
        alert.assigned_to = user_id
        alert.acknowledged_at = now
        db.flush()
        db.add(
            AlertStatusHistory(
                alert_id=alert.alert_id,
                old_status="NEW",
                new_status=new_status,
                changed_by=user_id,
                note=note,
            )
        )
    # Leave the remaining alerts unassigned and NEW: an alert queue with
    # nothing waiting in it would not demonstrate much.
    db.commit()


